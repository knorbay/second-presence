def language():return _language

def set_language(value):
    global _language
    if value not in ('tr','en'):raise ValueError(value)
    _language=value

def tr(text):
    text=str(text)
    if _language=='tr':return text
    if text in EN:return EN[text]
    for pattern,render in _TEMPLATES:
        match=pattern.fullmatch(text)
        if match:return render(match)
    # Replace source fragments once; never re-translate the English output.
    translated=_PATTERN.sub(lambda m:EN[m.group(0)],text)
    return re.sub(r'%(\d+)',r'\1%',translated)
